#!/usr/bin/env node
/**
 * Generates src/data/datasets/*.ts from the research files in .redesign/research/data.
 * Every series and every number in a takeaway line is read from those files; nothing is typed
 * by hand. Run from the repo root, then format:
 *
 *   node scripts/build-content-datasets.mjs [--research <dir>]
 *   npx prettier --write src/data/datasets
 *
 * The research directory is a local scratch area. When it is missing the committed output is
 * the source of truth and this script is only needed for the next annual refresh.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const researchFlag = args.indexOf('--research');
const researchDir = path.resolve(
  researchFlag >= 0 ? args[researchFlag + 1] : '.redesign/research/data',
);
const outDir = path.resolve('src/data/datasets');
mkdirSync(outDir, { recursive: true });

const read = (name) => JSON.parse(readFileSync(path.join(researchDir, `${name}.json`), 'utf8'));

const HEADER = `// GENERATED by scripts/build-content-datasets.mjs from the research data files.
// Do not edit by hand: change the inputs and run the script again.
`;

/** Formats a number with thousands separators and a fixed number of decimals. */
const num = (value, decimals = 0) =>
  value.toLocaleString('en-GB', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
/** Keeps at most `max` decimals but drops trailing zeros. */
const trim = (value, max = 1) => String(Number(value.toFixed(max)));
const pct = (value, max = 0) => `${trim(value, max)}%`;
const last = (list) => list[list.length - 1];

function assertSeries(id, series) {
  for (let i = 0; i < series.length; i += 1) {
    const p = series[i];
    if (!Number.isFinite(p.year)) throw new Error(`${id}: bad year at ${i}`);
    if (i > 0 && p.year <= series[i - 1].year) {
      throw new Error(`${id}: years not increasing at ${p.year}`);
    }
    for (const [key, value] of Object.entries(p)) {
      if (key !== 'year' && !Number.isFinite(value)) {
        throw new Error(`${id}: ${key} not finite at ${p.year}`);
      }
    }
  }
}

const lit = (value) => JSON.stringify(value);
const pointLit = (p) =>
  `{ ${Object.entries(p)
    .map(([k, v]) => `${k}: ${v}`)
    .join(', ')} }`;
const seriesLit = (series) => `[\n${series.map((p) => `  ${pointLit(p)},`).join('\n')}\n]`;

function metaLines(d, { sourceKey, takeaway, hopeful, decimals }) {
  return [
    `  id: ${lit(d.id)},`,
    `  title: ${lit(d.title)},`,
    `  unit: ${lit(d.unit)},`,
    `  source: ${lit(d.source)},`,
    `  citation: ${lit(d.citation)},`,
    `  url: ${lit(d.url)},`,
    `  landingPage: ${lit(d.landingPage ?? null)},`,
    `  retrieved: ${lit(d.retrieved)},`,
    `  sourceKey: ${lit(sourceKey)},`,
    `  takeaway: ${lit(takeaway)},`,
    `  notes: ${lit(d.notes)},`,
    `  hopeful: ${hopeful},`,
    `  decimals: ${decimals},`,
  ];
}

function emit({ file, constName, typeName, doc, body }) {
  writeFileSync(
    path.join(outDir, `${file}.ts`),
    `${HEADER}\nimport type { ${typeName} } from './types';\n\n/** ${doc} */\nexport const ${constName}: ${typeName} = {\n${body}\n};\n`,
  );
}

// 1. Temperature
{
  const d = read('global_temperature_anomaly');
  assertSeries(d.id, d.series);
  const { latest, warmestYear } = d.derived;
  const takeaway = `${warmestYear.year} was the warmest year in this record, ${num(warmestYear.value, 2)} °C above the 1951–1980 average; ${latest.year} was ${num(latest.value, 2)} °C above it, about ${num(latest.vsMean1880_1900, 1)} °C above 1880–1900 on our own re-basing.`;
  emit({
    file: 'temperature',
    constName: 'TEMPERATURE_ANOMALY',
    typeName: 'SeriesDataset',
    doc: 'Global mean surface temperature anomaly relative to 1951–1980 (NASA GISTEMP v4). Never label it "since pre-industrial".',
    body: [
      "  kind: 'series',",
      ...metaLines(d, { sourceKey: 'nasaGistemp', takeaway, hopeful: false, decimals: 2 }),
      '  comparisons: [],',
      `  series: ${seriesLit(d.series)},`,
    ].join('\n'),
  });
}

// 2. Mauna Loa CO2
{
  const d = read('atmospheric_co2_mauna_loa');
  const series = d.series.map(({ year, value }) => ({ year, value }));
  assertSeries(d.id, series);
  const { first, latest, increaseSinceFirst_pct, latestAnnualRise_ppm } = d.derived;
  const takeaway = `CO2 at Mauna Loa averaged ${num(latest.value, 2)} ppm in ${latest.year}, ${pct(increaseSinceFirst_pct)} above ${first.year}, and is still rising by about ${num(latestAnnualRise_ppm, 1)} ppm a year.`;
  emit({
    file: 'co2Atmosphere',
    constName: 'ATMOSPHERIC_CO2',
    typeName: 'SeriesDataset',
    doc: 'Annual mean atmospheric CO2 at Mauna Loa (NOAA GML, with Scripps for 1959–1974).',
    body: [
      "  kind: 'series',",
      ...metaLines(d, { sourceKey: 'noaaMaunaLoa', takeaway, hopeful: false, decimals: 2 }),
      '  comparisons: [],',
      `  series: ${seriesLit(series)},`,
    ].join('\n'),
  });
}

// 3. Fossil CO2
{
  const d = read('fossil_co2_emissions_world');
  assertSeries(d.id, d.series);
  const {
    latest,
    y1990,
    changeSince1990_pct,
    meanAnnualGrowth_2000_2010_pct,
    meanAnnualGrowth_last10_pct,
  } = d.derived;
  const takeaway = `Fossil CO2 reached ${num(latest.value, 1)} Gt in ${latest.year}, ${pct(changeSince1990_pct)} more than in ${y1990.year}, but yearly growth slowed from about ${num(meanAnnualGrowth_2000_2010_pct, 1)}% in 2000–2010 to about ${num(meanAnnualGrowth_last10_pct, 1)}% over the last ten years.`;
  emit({
    file: 'fossilEmissions',
    constName: 'FOSSIL_CO2_EMISSIONS',
    typeName: 'SeriesDataset',
    doc: 'Global fossil-fuel and industry CO2 (Global Carbon Budget 2025 via Our World in Data). Land-use change excluded.',
    body: [
      "  kind: 'series',",
      ...metaLines(d, { sourceKey: 'gcb2025Owid', takeaway, hopeful: false, decimals: 1 }),
      '  comparisons: [],',
      `  series: ${seriesLit(d.series)},`,
    ].join('\n'),
  });
}

// 4. Electricity mix
{
  const d = read('electricity_mix_world');
  assertSeries(d.id, d.series);
  const { latest, y2015 } = d.derived;
  const takeaway = `Renewables produced ${pct(latest.renewables, 1)} of the world's electricity in ${latest.year}, just ahead of coal at ${pct(latest.coal, 1)}; wind and solar together grew from ${pct(y2015.windAndSolar, 1)} in ${y2015.year} to ${pct(latest.windAndSolar, 1)}.`;
  const fields = [
    { key: 'renewables', label: 'Renewables', unit: '%' },
    { key: 'windAndSolar', label: 'Wind + solar', unit: '%' },
    { key: 'solar', label: 'Solar', unit: '%' },
    { key: 'wind', label: 'Wind', unit: '%' },
    { key: 'clean', label: 'Renewables + nuclear', unit: '%' },
    { key: 'fossil', label: 'Fossil fuels', unit: '%' },
    { key: 'coal', label: 'Coal', unit: '%' },
    { key: 'totalGenerationTWh', label: 'Total generation', unit: 'TWh' },
    { key: 'solarTWh', label: 'Solar generation', unit: 'TWh' },
    { key: 'windTWh', label: 'Wind generation', unit: 'TWh' },
  ];
  for (const f of fields) {
    if (!(f.key in d.series[0])) throw new Error(`electricity: missing ${f.key}`);
  }
  emit({
    file: 'electricityMix',
    constName: 'ELECTRICITY_MIX',
    typeName: 'MultiSeriesDataset',
    doc: 'World electricity generation by source, as shares of generation and in TWh (Ember).',
    body: [
      "  kind: 'multi',",
      ...metaLines(d, { sourceKey: 'ember2026', takeaway, hopeful: true, decimals: 1 }),
      `  fields: ${lit(fields)},`,
      `  series: ${seriesLit(d.series)},`,
    ].join('\n'),
  });
}

// 5. Solar module price
{
  const d = read('solar_module_price');
  assertSeries(d.id, d.series);
  const { latest, y2010, declineSince2010_pct } = d.derived;
  const takeaway = `A solar module cost about US$${num(latest.value, 2)} per watt in ${latest.year}, ${pct(declineSince2010_pct)} less than the US$${num(y2010.value, 2)} of ${y2010.year} (2025 dollars).`;
  emit({
    file: 'solarPrice',
    constName: 'SOLAR_MODULE_PRICE',
    typeName: 'SeriesDataset',
    doc: 'Solar photovoltaic module price in constant 2025 US dollars per watt (IRENA via Our World in Data). The panel only, not an installed system.',
    body: [
      "  kind: 'series',",
      ...metaLines(d, { sourceKey: 'irenaOwidSolarPrice', takeaway, hopeful: true, decimals: 2 }),
      '  comparisons: [],',
      `  series: ${seriesLit(d.series)},`,
    ].join('\n'),
  });
}

// 6. Solar capacity
{
  const d = read('solar_capacity_world');
  assertSeries(d.id, d.series);
  const { latest, multipleSince2015, addedInLatestYear_GW } = d.derived;
  const takeaway = `The world had ${num(latest.value, 0)} GW of solar capacity at the end of ${latest.year}, about ${num(multipleSince2015, 1)} times its 2015 level; ${num(addedInLatestYear_GW, 1)} GW of it was added in ${latest.year} alone.`;
  emit({
    file: 'solarCapacity',
    constName: 'SOLAR_CAPACITY',
    typeName: 'SeriesDataset',
    doc: 'Cumulative installed solar capacity worldwide in GW (IRENA via Our World in Data).',
    body: [
      "  kind: 'series',",
      ...metaLines(d, {
        sourceKey: 'irenaOwidSolarCapacity',
        takeaway,
        hopeful: true,
        decimals: 0,
      }),
      '  comparisons: [],',
      `  series: ${seriesLit(d.series)},`,
    ].join('\n'),
  });
}

// 7. EV sales share
{
  const d = read('ev_sales_share');
  assertSeries(d.id, d.series);
  const comparisons = Object.entries(d.byRegion).map(([label, series]) => {
    assertSeries(`${d.id}/${label}`, series);
    const id = label
      .toLowerCase()
      .replace(/\s*\(.*\)/, '')
      .replace(/[^a-z0-9]+/g, '-');
    return { id, label, series };
  });
  const { latest, y2015 } = d.derived;
  const china = comparisons.find((c) => c.label === 'China');
  const chinaPart = china ? `; in China it was ${pct(last(china.series).value)}` : '';
  const takeaway = `${pct(latest.value)} of new cars sold worldwide in ${latest.year} were electric (battery or plug-in hybrid), up from ${pct(y2015.value, 1)} in ${y2015.year}${chinaPart}. This is a share of sales, not of cars on the road.`;
  const comparisonLit = (c) =>
    `    { id: ${lit(c.id)}, label: ${lit(c.label)}, series: ${seriesLit(c.series)} },`;
  emit({
    file: 'evSales',
    constName: 'EV_SALES_SHARE',
    typeName: 'SeriesDataset',
    doc: 'Share of new cars sold that are electric, world and selected regions (IEA Global EV Outlook via Our World in Data).',
    body: [
      "  kind: 'series',",
      ...metaLines(d, { sourceKey: 'ieaOwidEv', takeaway, hopeful: true, decimals: 1 }),
      `  comparisons: [\n${comparisons.map(comparisonLit).join('\n')}\n  ],`,
      `  series: ${seriesLit(d.series)},`,
    ].join('\n'),
  });
}

// 8. Per-capita emissions
{
  const d = read('per_capita_emissions');
  const rows = d.regions.map((r) => ({
    id: r.id,
    name: r.name,
    best: r.best_tCO2PerPerson,
    bestBasis: r.bestBasis,
    bestYear: r.bestYear,
    consumptionCO2: r.consumptionCO2 ?? null,
    territorialCO2: r.territorialCO2 ?? null,
    ghgInclLandUse: r.ghgInclLandUse ?? null,
  }));
  const ids = new Set();
  for (const r of rows) {
    if (ids.has(r.id)) throw new Error(`per capita: duplicate ${r.id}`);
    ids.add(r.id);
    if (!Number.isFinite(r.best)) throw new Error(`per capita: ${r.id} has no value`);
  }
  const world = rows.find((r) => r.id === 'WORLD');
  const others = rows.filter((r) => r.id !== 'WORLD');
  const lo = others.reduce((a, b) => (b.best < a.best ? b : a));
  const hi = others.reduce((a, b) => (b.best > a.best ? b : a));
  const takeaway = `The average person in the world accounts for about ${num(world.best, 1)} t of CO2 a year; among the ${others.length} regions here it runs from ${num(lo.best, 1)} t (${lo.name}) to ${num(hi.best, 1)} t (${hi.name}). These include industry and public services, so they are not lifestyle footprints.`;
  const rowLit = (r) =>
    `    { id: ${lit(r.id)}, name: ${lit(r.name)}, best: ${r.best}, bestBasis: ${lit(r.bestBasis)}, bestYear: ${r.bestYear}, consumptionCO2: ${lit(r.consumptionCO2)}, territorialCO2: ${lit(r.territorialCO2)}, ghgInclLandUse: ${lit(r.ghgInclLandUse)} },`;
  emit({
    file: 'perCapita',
    constName: 'PER_CAPITA_EMISSIONS',
    typeName: 'SnapshotDataset',
    doc: 'Latest emissions per person by country or region (Global Carbon Budget 2025 and Jones et al. 2025 via Our World in Data).',
    body: [
      "  kind: 'snapshot',",
      ...metaLines(d, { sourceKey: 'gcbOwidPerCapita', takeaway, hopeful: false, decimals: 1 }),
      `  rows: [\n${rows.map(rowLit).join('\n')}\n  ],`,
    ].join('\n'),
  });
}

// Barrel
const barrel = `${HEADER}
import { ATMOSPHERIC_CO2 } from './co2Atmosphere';
import { ELECTRICITY_MIX } from './electricityMix';
import { EV_SALES_SHARE } from './evSales';
import { FOSSIL_CO2_EMISSIONS } from './fossilEmissions';
import { PER_CAPITA_EMISSIONS } from './perCapita';
import { SOLAR_CAPACITY } from './solarCapacity';
import { SOLAR_MODULE_PRICE } from './solarPrice';
import { TEMPERATURE_ANOMALY } from './temperature';
import type { Dataset } from './types';

export * from './types';
export {
  ATMOSPHERIC_CO2,
  ELECTRICITY_MIX,
  EV_SALES_SHARE,
  FOSSIL_CO2_EMISSIONS,
  PER_CAPITA_EMISSIONS,
  SOLAR_CAPACITY,
  SOLAR_MODULE_PRICE,
  TEMPERATURE_ANOMALY,
};

/** The eight bundled datasets, in the order the Impact page shows them. */
export const DATASETS: readonly Dataset[] = [
  ATMOSPHERIC_CO2,
  TEMPERATURE_ANOMALY,
  FOSSIL_CO2_EMISSIONS,
  ELECTRICITY_MIX,
  SOLAR_MODULE_PRICE,
  SOLAR_CAPACITY,
  EV_SALES_SHARE,
  PER_CAPITA_EMISSIONS,
];

export const DATASET_BY_ID: ReadonlyMap<string, Dataset> = new Map(
  DATASETS.map((dataset) => [dataset.id, dataset]),
);
`;
writeFileSync(path.join(outDir, 'index.ts'), barrel);
console.log(`wrote 8 dataset modules and index.ts to ${path.relative('.', outDir)}`);
